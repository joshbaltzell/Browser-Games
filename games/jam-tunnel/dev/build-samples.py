#!/usr/bin/env python3
"""Rebuild games/jam-tunnel/samples/*.js from the FluidR3_GM sound font.

The game must open by double-clicking index.html, so it can't fetch audio files.
Instead each instrument's samples live in a plain script (samples/<name>.js) as base64 MP3s,
and audio.js adds the script tag only when a song needs that instrument.

Sources (both are conversions of FluidR3_GM by Frank Wen, CC BY 3.0):
  - melodic instruments: https://github.com/gleitz/midi-js-soundfonts
  - drum kit: https://github.com/surikov/webaudiofontdata
  - grand piano: Salamander Grand Piano by Alexander Holm, CC BY 3.0, as MP3s from
    https://github.com/Tonejs/audio (recorded every three semitones)

Usage: python3 dev/build-samples.py [cache_dir]
"""
import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, '..', 'samples')
CACHE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '.cache')

# name in the game -> (FluidR3 instrument, lowest MIDI note, highest MIDI note)
MELODIC = {
    'guitar': ('overdriven_guitar', 40, 67),
    'distguitar': ('distortion_guitar', 40, 67),
    'bass': ('electric_bass_finger', 26, 52),
    'upright': ('acoustic_bass', 26, 52),
    'synthbass': ('synth_bass_1', 26, 52),
    'organ': ('drawbar_organ', 48, 76),
    'piano': ('acoustic_grand_piano', 45, 88),
    'epiano': ('electric_piano_1', 45, 80),
    'strings': ('string_ensemble_1', 44, 82),
    'warmpad': ('pad_2_warm', 45, 76),
    'musicbox': ('music_box', 58, 88),
    'flute': ('flute', 58, 88),
    'vibes': ('vibraphone', 53, 86),
    'acoustic': ('acoustic_guitar_steel', 40, 76),
    'fiddle': ('fiddle', 55, 88),
    'banjo': ('banjo', 48, 84),
    'cleanguitar': ('electric_guitar_clean', 40, 80),
    'harmonica': ('harmonica', 55, 86),
}
# name in the game -> General MIDI drum note
KIT = {'kick': 36, 'snare': 38, 'hat': 42, 'openhat': 46, 'tomlow': 45, 'tomhigh': 48, 'crash': 49}

PC = {'C': 0, 'Db': 1, 'D': 2, 'Eb': 3, 'E': 4, 'F': 5, 'Gb': 6, 'G': 7, 'Ab': 8, 'A': 9, 'Bb': 10, 'B': 11}


def fetch(url, name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        print('downloading', url)
        urllib.request.urlretrieve(url, path)
    with open(path) as f:
        return f.read()


def midi(name):
    m = re.match(r'([A-G]b?)(-?\d)$', name)
    return 12 * (int(m.group(2)) + 1) + PC[m.group(1)]


HEADER = (
    '// Instrument samples: FluidR3_GM by Frank Wen, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/),\n'
    '// converted by midi-js-soundfonts (gleitz) and WebAudioFont (surikov).\n'
    '// Generated by dev/build-samples.py; trimmed to the notes Jam Tunnel uses. Do not edit by hand.\n'
)
os.makedirs(OUT_DIR, exist_ok=True)


def write(key, data, header=HEADER):
    path = os.path.join(OUT_DIR, key + '.js')
    with open(path, 'w') as f:
        f.write(header + '(window.JT_SAMPLES = window.JT_SAMPLES || {})[%s] = %s;\n' % (json.dumps(key), json.dumps(data)))
    print(key, len(data), 'samples', os.path.getsize(path), 'bytes')

for key, (inst, lo, hi) in MELODIC.items():
    src = fetch('https://gleitz.github.io/midi-js-soundfonts/FluidR3_GM/%s-mp3.js' % inst, inst + '.js')
    notes = {midi(n): b for n, b in re.findall(r'"([A-G]b?-?\d)":\s*"data:audio/mp3;base64,([^"]+)"', src)
             if lo <= midi(n) <= hi}
    write(key, {str(k): v for k, v in sorted(notes.items())})

kit = {}
for name, note in KIT.items():
    src = fetch('https://surikov.github.io/webaudiofontdata/sound/128%d_0_FluidR3_GM_sf2_file.js' % note, 'drum%d.js' % note)
    kit[name] = re.search(r"file:'([^']+)'", src).group(1)
write('kit', kit)

# Salamander grand, used for the darkened trap piano
import base64
SAL_NAMES = {'C': 0, 'Ds': 3, 'Fs': 6, 'A': 9}
grand = {}
for octave in range(1, 7):
    for name, pc in SAL_NAMES.items():
        note = 12 * (octave + 1) + pc
        if not 33 <= note <= 84:
            continue
        path = os.path.join(CACHE, 'salamander-%s%d.mp3' % (name, octave))
        if not os.path.exists(path):
            urllib.request.urlretrieve('https://tonejs.github.io/audio/salamander/%s%d.mp3' % (name, octave), path)
        with open(path, 'rb') as f:
            grand[str(note)] = base64.b64encode(f.read()).decode()
write('grand', grand, '// Salamander Grand Piano by Alexander Holm, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/),\n'
      '// MP3s from https://github.com/Tonejs/audio. Generated by dev/build-samples.py. Do not edit by hand.\n')
